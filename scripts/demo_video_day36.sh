#!/usr/bin/env bash
# Демо для записи экрана (день 36): ОДИН видимый процесс CLI-ассистента,
# в него «печатаются» команды — как будто вводит человек. Показывает:
#   /help                — интерактивная сессия и меню команд;
#   /git, /files         — MCP (studio/mcp_servers/git_branch.py);
#   /help <вопрос> ...   — RAG по документации + контекст проекта;
#   вопрос о структуре проекта и архитектуре пайплайна;
#   выход.
#
# Запуск:  scripts/demo_video_day36.sh
# Пауза после вопроса — под ответ модели (можно увеличить/уменьшить).
set -u
cd "$(dirname "$0")/.." || exit 1
PY=.venv/bin/python

QUESTIONS=(
  "/help"
  "/git"
  "/files"
  "/help какая сейчас git-ветка и какие файлы изменены в рабочем дереве?"
  "/help как устроена структура проекта и где лежит архитектура пайплайна?"
)
PAUSE=("4" "3" "3" "16" "20")

echo "================ ДЕМО: CLI-ассистент — /help + RAG + MCP git ================"
sleep 2

run() {
  local i=0 q
  for q in "${QUESTIONS[@]}"; do
    printf '%s\n' "$q"
    # время на «ответ» — берём из PAUSE по индексу
    sleep "${PAUSE[$i]}"
    i=$((i + 1))
  done
  printf 'exit\n'
}

# Вопросы «печатаются» в тот же видимый процесс — живая сессия
run | $PY dev_assistant.py
sleep 1
echo "Демо завершено."
